#!/usr/bin/env python3
"""Rebuild Markdown task board from per-task journals (stdlib only).

Does not query Git; task files must contain verified Git statuses.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASKS = ROOT / "docs/progress/tasks"
BOARD = ROOT / "docs/progress/TASK_BOARD.md"
FIELDS = ("task_id", "date", "title", "summary", "changed_files", "module", "owner", "status", "branch", "commit", "push", "merge", "tests", "issues")


def metadata(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"Missing frontmatter: {path}")
    data = {}
    for line in text.split("---", 2)[1].splitlines():
        if ":" in line:
            key, val = line.split(":", 1)
            data[key.strip()] = val.strip().strip('"')
    for key in FIELDS:
        if key not in data:
            raise ValueError(f"Missing {key} in {path.name}")
    if data["status"] not in {"planned", "in_progress", "blocked", "in_review", "done"}:
        raise ValueError(f"Unknown status in {path.name}")
    return data


def safe(x: str) -> str:
    return x.replace("|", "\\|").replace("\n", " ")


def main() -> None:
    rows = [metadata(p) for p in TASKS.glob("EDU-*.md")]
    rows.sort(key=lambda r: r["task_id"])
    lines = ["# EduOps 360 — Task Board", "", "Generated by `python scripts/sync_task_board.py` from `docs/progress/tasks/*.md`. **Do not manually edit.**", "", "Commit/push/merge fields must be backed by verified Git evidence in each task journal.", "", "| Task | Date | Work / changes | Files | Owner | Status | Tests | Commit | Push | Merge | Problems |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        cells = [r[k] for k in ("task_id", "date", "summary", "changed_files", "owner", "status", "tests", "commit", "push", "merge", "issues")]
        lines.append("| " + " | ".join(map(safe, cells)) + " |")
    if not rows:
        lines.append("| — | — | — | — | — | — | — | — | — | — | — |")
    BOARD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {BOARD.relative_to(ROOT)} with {len(rows)} task(s)")


if __name__ == "__main__":
    main()
